_HANGUL_RE = re.compile(r"[\uac00-\ud7a3]")
_LATIN_DIGIT_TRIM = re.compile(r"[A-Za-z0-9][A-Za-z0-9.\- ]*")


def encar_option_ru(code: object) -> Optional[str]:
    raw = str(code or "").strip()
    if not raw:
        return None
    key = re.sub(r"^0+", "", raw) or "0"
    return ENCAR_OPTION_CODE_RU.get(key)


def translate_ko_option_label(raw: str) -> Optional[str]:
    s = (raw or "").strip()
    if not s:
        return None
    out = s
    for ko, ru in _KO_OPTION_PAIRS:
        if ko in out:
            out = out.replace(ko, ru)
    out = re.sub(r"\s+", " ", out).strip(" ·,;/-")
    if not out or _HANGUL_RE.search(out):
        return None
    return out


def sanitize_trim_name(raw: str) -> Optional[str]:
    s = (raw or "").strip()
    if not s:
        return None
    if not _HANGUL_RE.search(s):
        return s
    cleaned = _HANGUL_RE.sub(" ", s)
    cleaned = re.sub(r"\s+", " ", cleaned).strip(" ·,;/-")
    if cleaned and not _HANGUL_RE.search(cleaned) and len(cleaned) >= 2:
        return cleaned
    m = _LATIN_DIGIT_TRIM.search(s)
    if m:
        token = m.group(0).strip(" ·,;/-")
        if token:
            return token
    return None
